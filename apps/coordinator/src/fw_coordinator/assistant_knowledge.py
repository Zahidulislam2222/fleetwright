"""Approved knowledge for the console help assistant: public documentation split into sections and a
small BM25 keyword index over them. No embeddings or vector store: the corpus is a few hundred
sections, and keyword retrieval is deterministic, free and easy to audit (global Rule 24: simplest
effective design). The index file is generated by tools/dev/build_assistant_knowledge.py and checked
against the source documents by a test, so stale or deleted content cannot linger."""

from __future__ import annotations

import hashlib
import json
import math
import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any

KNOWLEDGE_FILE = "assistant-knowledge.json"
SECTION_MAX_CHARS = 1400
SECTION_MIN_CHARS = 60
_HEADING = re.compile(r"^(#{1,4})\s+(.+?)\s*#*\s*$")
_WORD = re.compile(r"[a-z0-9]+")
_LINK = re.compile(r"\[([^\]]+)\]\([^)]+\)")
_STOP = frozenset(
    [
        "a",
        "an",
        "and",
        "are",
        "as",
        "at",
        "be",
        "by",
        "can",
        "do",
        "does",
        "for",
        "from",
        "has",
        "have",
        "how",
        "i",
        "if",
        "in",
        "is",
        "it",
        "its",
        "me",
        "my",
        "no",
        "not",
        "of",
        "on",
        "or",
        "our",
        "so",
        "than",
        "that",
        "the",
        "their",
        "then",
        "there",
        "these",
        "this",
        "to",
        "was",
        "we",
        "what",
        "when",
        "where",
        "which",
        "who",
        "why",
        "will",
        "with",
        "you",
        "your",
    ]
)
# BM25 parameters (standard values).
_K1 = 1.2
_B = 0.75


_CRLF, _LF = chr(13) + chr(10), chr(10)


@dataclass(frozen=True)
class Section:
    id: str
    source: str
    heading: str
    text: str


def tokens(text: str) -> list[str]:
    return [w for w in _WORD.findall(text.lower()) if len(w) > 1 and w not in _STOP]


def _plain(markdown: str) -> str:
    """Readable text: links keep their label, code fences and table rules are dropped."""
    out: list[str] = []
    fenced = False
    for line in markdown.splitlines():
        if line.strip().startswith("```"):
            fenced = not fenced
            continue
        if fenced or re.fullmatch(r"\s*\|?[\s:|-]+\|?\s*", line):
            continue
        out.append(_LINK.sub(r"\1", line).rstrip())
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def _split(text: str) -> list[str]:
    """Paragraph-aligned pieces no longer than SECTION_MAX_CHARS."""
    pieces: list[str] = []
    current = ""
    for raw in text.split("\n\n"):
        rest = raw.strip()
        if not rest:
            continue
        while len(rest) > SECTION_MAX_CHARS:
            cut = rest.rfind(" ", 0, SECTION_MAX_CHARS)
            cut = cut if cut > SECTION_MAX_CHARS // 2 else SECTION_MAX_CHARS
            if current:
                pieces.append(current)
                current = ""
            pieces.append(rest[:cut].strip())
            rest = rest[cut:].strip()
        if current and len(current) + len(rest) + 2 > SECTION_MAX_CHARS:
            pieces.append(current)
            current = rest
        else:
            current = f"{current}\n\n{rest}" if current else rest
    if current:
        pieces.append(current)
    return pieces


def sections_of(source: str, markdown: str) -> list[Section]:
    found: list[Section] = []
    title = source
    heading = source
    body: list[str] = []

    def flush() -> None:
        text = _plain("\n".join(body))
        for n, piece in enumerate(_split(text)):
            if len(piece) >= SECTION_MIN_CHARS:
                label = heading if heading == title else f"{title} — {heading}"
                found.append(Section(f"{source}#{len(found)}-{n}", source, label, piece))

    for line in markdown.splitlines():
        m = _HEADING.match(line)
        if m:
            flush()
            body = []
            heading = _LINK.sub(r"\1", m.group(2)).replace("`", "")
            if len(m.group(1)) == 1:
                title = heading
            continue
        body.append(line)
    flush()
    return found


def build(root: Path, sources: list[str], version: str) -> dict[str, Any]:
    """The index file content for the approved sources (paths relative to the repository root)."""
    digests: dict[str, str] = {}
    sections: list[dict[str, str]] = []
    for source in sources:
        # Line endings are normalised so a Windows checkout (CRLF) and CI (LF) agree on the digest.
        text = (root / source).read_bytes().decode("utf-8").replace(_CRLF, _LF)
        digests[source] = hashlib.sha256(text.encode("utf-8")).hexdigest()
        sections.extend(vars(s) for s in sections_of(source, text))
    return {"version": version, "sources": digests, "sections": sections}


class Knowledge:
    """BM25 over section text, with the heading counted twice (titles carry the topic)."""

    def __init__(self, data: dict[str, Any]) -> None:
        self.version = str(data["version"])
        self.sections = [Section(**s) for s in data["sections"]]
        self._docs = [tokens(f"{s.heading} {s.heading} {s.text}") for s in self.sections]
        self._tf = [Counter(d) for d in self._docs]
        self._avg = sum(len(d) for d in self._docs) / max(len(self._docs), 1)
        df: Counter[str] = Counter()
        for d in self._docs:
            df.update(set(d))
        n = len(self._docs)
        self._idf = {w: math.log(1 + (n - c + 0.5) / (c + 0.5)) for w, c in df.items()}

    @classmethod
    def load(cls, config_dir: Path) -> Knowledge:
        return cls(json.loads((config_dir / KNOWLEDGE_FILE).read_text(encoding="utf-8")))

    def search(self, query: str, k: int) -> list[Section]:
        terms = set(tokens(query))
        if not terms:
            return []
        scored: list[tuple[float, int]] = []
        for i, tf in enumerate(self._tf):
            length = len(self._docs[i])
            score = 0.0
            for w in terms:
                f = tf.get(w, 0)
                if f:
                    score += self._idf[w] * f * (_K1 + 1) / (f + _K1 * (1 - _B + _B * length / self._avg))
            if score > 0:
                scored.append((score, i))
        scored.sort(key=lambda x: (-x[0], x[1]))
        return [self.sections[i] for _, i in scored[:k]]
